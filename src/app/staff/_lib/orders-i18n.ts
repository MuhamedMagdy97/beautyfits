export const ORDERS_DICTIONARIES = { ar, en };

/** The shell, catalog and orders texts in the current language. */
export function useOrdersT() {
  const { t, c, english } = useCatalogT();
  return { t, c, o: english ? en : ar, english };
}

/** A status label from the order or return maps, else the code. */
function statusLabel(c: CatalogDictionary, o: OrdersDictionary, status: unknown): string {
  const code = String(status ?? "");
  return o.returnStatuses[code] ?? c.statuses[code] ?? code;
}

/** A localized message for an API failure of these screens. */
export function ordersError(
  t: Dictionary,
  c: CatalogDictionary,
  o: OrdersDictionary,
  error: unknown,
): string {
  if (error instanceof StaffApiError) {
    const reason = String(error.details.reason ?? "");
    if (o.conflicts[reason]) {
      return o.conflicts[reason];
    }
    if (error.code === "ORDER_STATE_INVALID" || error.code === "RETURN_STATE_INVALID") {
      return o.stateInvalid.replace("{status}", statusLabel(c, o, error.details.status));
    }
    if (error.code === "ORDER_CANCELLATION_NOT_ALLOWED") {
      return reason && c.conflicts[reason]
        ? c.conflicts[reason]
        : o.cancellationNotAllowed.replace("{status}", statusLabel(c, o, error.details.status));
    }
  }
  return catalogError(t, c, error);
}

/** The customer's account state: deleted by the customer, no account, or the account status. */
export function accountLabel(
  o: OrdersDictionary,
  customer: { accountStatus: string | null; anonymized: boolean },
): string {
  if (customer.anonymized) return o.anonymized;
  if (!customer.accountStatus) return o.noAccount;
  return o.accountStatuses[customer.accountStatus] ?? customer.accountStatus;
}
