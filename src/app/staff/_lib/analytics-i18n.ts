export const ANALYTICS_DICTIONARIES = { ar, en };

/** The shell, catalog and TASK-052A texts in the current language. */
export function useAnalyticsT() {
  const { t, c, english } = useCatalogT();
  const x = english ? en : ar;
  /** Localized API failure, using the employee-management reason when there is one. */
  const fail = (error: unknown) => {
    const reason = error instanceof StaffApiError ? String(error.details.reason ?? "") : "";
    return x.errors[reason] ?? catalogError(t, c, error);
  };
  return { t, c, x, english, fail };
}
